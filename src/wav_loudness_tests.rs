use super::{balancing_expression, handle_midi_message, init_synth, render_samples, SAMPLE_RATE};
use midly::num::{u4, u7};
use midly::MidiMessage;
use oxisynth::{MidiEvent, Synth};

static SF2_BYTES: &[u8] = include_bytes!("../fonts/GeneralUser_GS.sf2");

/// A short do-re-mi-sol-la-do phrase around middle C.
const PHRASE: [u8; 6] = [60, 62, 64, 67, 69, 72];
const EXPRESSION_CONTROLLER: u8 = 11;
const VOLUME_CONTROLLER: u8 = 7;

/// The phrase's loudness, in dB: each note's loudest 100 ms (so a plucked
/// note's decay doesn't count against it), averaged over the phrase.
fn phrase_loudness_db(synth: &mut Synth) -> f64 {
    let note_samples = SAMPLE_RATE as usize / 2;
    let window = SAMPLE_RATE as usize / 10;
    let energy: f64 = PHRASE
        .iter()
        .map(|&key| {
            synth
                .send_event(MidiEvent::NoteOn {
                    channel: 0,
                    key,
                    vel: 100,
                })
                .ok();
            let (mut left, mut right) = (Vec::new(), Vec::new());
            render_samples(synth, note_samples, &mut left, &mut right);
            synth
                .send_event(MidiEvent::NoteOff { channel: 0, key })
                .ok();
            let power: Vec<f64> = left
                .iter()
                .zip(&right)
                .map(|(l, r)| f64::from(*l).powi(2) + f64::from(*r).powi(2))
                .collect();
            (0..note_samples - window)
                .step_by(SAMPLE_RATE as usize / 100)
                .map(|start| power.iter().skip(start).take(window).sum::<f64>())
                .fold(0.0, f64::max)
        })
        .sum();
    10.0 * (energy / (PHRASE.len() * window * 2) as f64).log10()
}

fn send_controller(synth: &mut Synth, ctrl: u8, value: u8) {
    synth
        .send_event(MidiEvent::ControlChange {
            channel: 0,
            ctrl,
            value,
        })
        .ok();
}

/// `program`'s loudness as the synth plays it, before balancing.
fn raw_loudness_db(program: u8) -> f64 {
    let mut synth = init_synth(SF2_BYTES).unwrap();
    synth
        .send_event(MidiEvent::ProgramChange {
            channel: 0,
            program_id: program,
        })
        .ok();
    send_controller(&mut synth, VOLUME_CONTROLLER, 127);
    send_controller(&mut synth, EXPRESSION_CONTROLLER, 127);
    phrase_loudness_db(&mut synth)
}

/// `program`'s loudness as a rendered score plays it, after balancing.
fn balanced_loudness_db(program: u8) -> f64 {
    let mut synth = init_synth(SF2_BYTES).unwrap();
    let channel = u4::new(0);
    handle_midi_message(
        &mut synth,
        channel,
        &MidiMessage::ProgramChange {
            program: u7::new(program),
        },
    );
    handle_midi_message(
        &mut synth,
        channel,
        &MidiMessage::Controller {
            controller: u7::new(VOLUME_CONTROLLER),
            value: u7::new(127),
        },
    );
    phrase_loudness_db(&mut synth)
}

#[test]
fn every_instrument_default_and_piano_play_at_about_the_same_loudness() {
    // Piano, nylon guitar, violin, cello, shamisen, koto, harmonica, choir.
    let programs = [0u8, 24, 40, 42, 106, 107, 22, 52];
    let loudness: Vec<f64> = programs.iter().map(|&p| balanced_loudness_db(p)).collect();
    let loudest = loudness.iter().copied().fold(f64::NEG_INFINITY, f64::max);
    let quietest = loudness.iter().copied().fold(f64::INFINITY, f64::min);
    assert!(
        loudest - quietest < 1.0,
        "loudness spread {:.2} dB: {programs:?} -> {loudness:.2?}",
        loudest - quietest
    );
}

#[test]
fn the_quietest_program_is_left_unattenuated() {
    assert_eq!((0..128).map(balancing_expression).max(), Some(127));
}

#[test]
#[ignore = "rewrites src/wav_loudness_table.rs from the bundled soundfont"]
fn regenerate_program_loudness_table() {
    let piano_db = raw_loudness_db(0);
    let rows: String = (0..128u8)
        .map(|program| {
            format!(
                "    {:.2}, // {program}\n",
                raw_loudness_db(program) - piano_db
            )
        })
        .collect();
    let table = format!(
        "// Generated by `regenerate_program_loudness_table` in src/wav_loudness_tests.rs.\n[\n{rows}]\n"
    );
    std::fs::write(
        concat!(env!("CARGO_MANIFEST_DIR"), "/src/wav_loudness_table.rs"),
        table,
    )
    .unwrap();
}
