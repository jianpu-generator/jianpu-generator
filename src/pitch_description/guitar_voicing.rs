use itertools::Itertools;

/// One guitar chord shape from the vendored chords-db (`vendor/chords-db/`),
/// strings ordered low E to high E. `frets` are relative to `base_fret`:
/// `-1` = muted, `0` = open, `1` = the diagram's first fret row (which is
/// absolute fret `base_fret`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GuitarVoicing {
    pub frets: [i8; 6],
    pub base_fret: u8,
    /// Relative fret rows held down by a barre.
    pub barres: &'static [u8],
}

impl GuitarVoicing {
    /// The absolute fret of each string, `None` for a muted one (`0` = open).
    pub fn absolute_frets(&self) -> [Option<u8>; 6] {
        self.frets.map(|fret| match u8::try_from(fret) {
            Err(_) => None,
            Ok(0) => Some(0),
            Ok(relative) => Some(relative + self.base_fret - 1),
        })
    }

    /// Absolute frets as `"x 3 2 0 1 0"` — muted strings as `x`.
    pub fn frets_label(&self) -> String {
        self.absolute_frets()
            .iter()
            .map(|fret| fret.map_or_else(|| "x".to_string(), |fret| fret.to_string()))
            .join(" ")
    }
}

pub(crate) struct GuitarVoicingEntry {
    root_pitch_class: u8,
    suffix: &'static str,
    voicing: GuitarVoicing,
}

// Generated by `build.rs` from `vendor/chords-db/guitar.json`: defines
// `GUITAR_VOICINGS`, every chords-db position of every chord, in chords-db's
// order.
include!(concat!(env!("OUT_DIR"), "/guitar_voicings_generated.rs"));

/// Every chords-db position of a chord, most common first (usually the open
/// shape, then shapes further up the neck); empty when chords-db has none.
/// `root_pitch_class` is 0 = C ... 11 = B; `suffix` is a chords-db suffix
/// (`"major"`, `"m7"`, `"/G"`, `"m/C"`, ...).
pub(crate) fn find_guitar_voicings(
    root_pitch_class: i8,
    suffix: &str,
) -> Vec<&'static GuitarVoicing> {
    GUITAR_VOICINGS
        .iter()
        .filter(|entry| {
            i8::try_from(entry.root_pitch_class) == Ok(root_pitch_class) && entry.suffix == suffix
        })
        .map(|entry| &entry.voicing)
        .collect()
}

/// chords-db's name for a slash chord's bass note, by pitch class.
pub(crate) fn chords_db_bass_name(pitch_class: i8) -> &'static str {
    match pitch_class {
        1 => "C#",
        2 => "D",
        3 => "D#",
        4 => "E",
        5 => "F",
        6 => "F#",
        7 => "G",
        8 => "G#",
        9 => "A",
        10 => "Bb",
        11 => "B",
        _ => "C",
    }
}
